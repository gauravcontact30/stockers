-- ---------------------------------------------------------------------------
-- The stock catalogue
-- ---------------------------------------------------------------------------
--
-- Every listed company, by symbol, name, scrip code and ISIN — what the directory and every stock
-- picker search against.
--
-- Provisioned here, and NOT yet read by the application: the catalogue is built by
-- `scripts/build-catalogue.mjs` from the exchange's own scrip master into `app/data/`, and it is
-- read from there. That is deliberate and not a bug — the catalogue is derived reference data, it
-- ships with the build, and reading ~4,950 rows from a bundled file is faster than querying for
-- them on every search. The table is here for a deployment that would rather keep it in Postgres
-- and refresh it without a redeploy.

create table if not exists public.stocks (
  -- The exchange ticker, upper-cased. The same key `portfolio_holdings.symbol` uses.
  symbol text primary key,
  name text not null,
  -- BSE's numeric scrip code, as text — it is an identifier, not a quantity, and some carry
  -- leading zeroes that a number would eat.
  scrip_code text,
  isin text,
  sector text,
  -- 'Large' | 'Mid' | 'Small', as classified by the catalogue build.
  cap_tier text,
  -- Used to fetch the company's logo.
  domain text,
  updated_at text not null
);

create index if not exists stocks_name_idx on public.stocks (lower(name));
create index if not exists stocks_isin_idx on public.stocks (isin) where isin is not null;

-- Unlike every other table here, this one holds no personal data at all — it is a public list of
-- listed companies. RLS is still enabled with no policies, because nothing in this application
-- reads it from the browser and a table that is open "because it is harmless" is one policy change
-- away from being the pattern somebody copies onto a table that is not.
alter table public.stocks enable row level security;
revoke all on public.stocks from anon, authenticated;

-- ---------------------------------------------------------------------------
-- ai_calls
-- ---------------------------------------------------------------------------
--
-- One row per model call: what was asked, how long it took, what it consumed and — the point of
-- the table — whether the reader ended up with a written read or the composed one.
--
-- The application does not need this table to observe itself. `app/lib/ai-telemetry.ts` always
-- keeps the last couple of thousand calls in the process's own memory, so the AI Operations panel
-- works on a fresh clone and on a deployment that has never applied this file. What that store
-- cannot do is survive a restart, and on a serverless host it cannot see the calls the *other*
-- instances made — which is exactly the deployment where an operator most needs the figures. This
-- table is the durable half, and the panel says which of the two it is reading.
--
-- Writes are fire-and-forget and a missing table latches the writer off after one attempt, so
-- never applying this costs the history and nothing else.

create table if not exists public.ai_calls (
  -- Generated by the application (`ai_<base36 time>_<random>`), like every other id here, so the
  -- two stores mint ids the same way.
  id text primary key,

  -- The exact instant, ISO-8601 UTC, as text — for the same reason `analytics_events.at` is text.
  -- ISO-8601 UTC sorts lexically in chronological order, so `order by at desc` is "newest first".
  at text not null,

  -- The IST calendar date `at` falls on. Stored rather than derived because every query here is
  -- "since this day" and every aggregate groups by it.
  day text not null,

  -- Which call site asked: 'board-read', 'intel-search', 'stock-analysis' and so on. Deliberately
  -- not constrained to a list — these name call sites in the code, and adding one should not need
  -- a migration. The report groups by whatever it finds.
  feature text not null,

  -- The model asked for, or null when nothing was attempted (no key configured).
  model text,

  -- What the reader ended up with. Constrained here as well as in TypeScript: this is the column
  -- every aggregate branches on, and an unrecognised value would be counted as nothing at all.
  --   'ok'           the model answered and the answer was usable
  --   'unusable'     it answered, but the reply could not be used — the reader got the composed read
  --   'failed'       non-2xx, a network error, or the timeout
  --   'unconfigured' no API key; nothing was attempted and nothing was spent
  outcome text not null check (outcome in ('ok', 'unusable', 'failed', 'unconfigured')),

  -- The HTTP status, when there was a response. Null for a timeout, a network error, or no key.
  status integer,

  -- Wall-clock duration in milliseconds, including the network. Null when nothing was attempted.
  -- For a streamed call this is time to the end of the stream, not to the first token.
  ms integer,

  -- Tokens as OpenRouter reported them, and what it said the call cost in USD. All three are
  -- nullable rather than defaulting to zero: a failed call reports no usage, and a zero would be
  -- indistinguishable from a call that genuinely consumed nothing. Cost is read from the reply
  -- rather than estimated from a price table, which would be wrong the first time a model is
  -- repriced and nobody would notice.
  prompt_tokens integer,
  completion_tokens integer,
  cost_usd double precision,

  streamed boolean not null default false,

  -- The failure message, clipped by the writer. Never a request or response body: a completion's
  -- body can contain the prompt, and a prompt can contain whatever a reader typed into the search.
  error text
);

-- Every read is "since this day, newest first".
create index if not exists ai_calls_day_idx on public.ai_calls (day, at desc);

-- Nothing in this application reads this table from the browser — the panel goes through
-- `/api/admin/ai-usage`, which re-checks the caller is an admin — so the anon and authenticated
-- roles get nothing, as with every other table here.
alter table public.ai_calls enable row level security;
revoke all on public.ai_calls from anon, authenticated;
